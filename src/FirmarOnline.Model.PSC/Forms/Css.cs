namespace FirmarOnline.Model.PSC.Forms
{
    /// <summary>
    /// Propiedades CSS.
    /// </summary>
    public class Css
    {
        /// <summary>
        /// Alineación.
        /// </summary>
        public string Align { get; set; }

        /// <summary>
        /// Color de fondo.
        /// </summary>
        public string BackgroundColor { get; set; }

        /// <summary>
        /// Borde.
        /// </summary>
        public string Border { get; set; }

        /// <summary>
        /// Celdas comparten bordes.
        /// </summary>
        public string BorderCollapse { get; set; }

        /// <summary>
        /// Color.
        /// </summary>
        public string Color { get; set; }

        /// <summary>
        /// Tipo de visualización
        /// </summary>
        public string Display { get; set; }

        /// <summary>
        /// Ubicación con respecto al contenedor.
        /// </summary>
        public string Float { get; set; }

        /// <summary>
        /// Familia de la fuente.
        /// </summary>
        public string FontFamily { get; set; }

        /// <summary>
        /// Tamaño de la fuente.
        /// </summary>
        public string FontSize { get; set; }

        /// <summary>
        /// Peso de la fuente.
        /// </summary>
        public string FontWeight { get; set; }

